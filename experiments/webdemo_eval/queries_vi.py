def unaccented(text: str) -> str:
    """The sentence as typed without diacritics (đ -> d)."""
    nfd = unicodedata.normalize("NFD", text.replace("đ", "d").replace("Đ", "D"))
    return "".join(c for c in nfd if unicodedata.category(c) != "Mn")
